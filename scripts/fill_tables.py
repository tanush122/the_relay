"""Copy the computed tables into docs/WRITEUP.md, so no number is ever retyped by hand.

Replaces everything under the "## Results tables" heading with Table 1 (from the newest
probe run plus real 429s in the traces) and Tables 2a, 2b, 3 and the earlier-runs side
table (from data/results.csv). Run it again whenever results.csv changes.

  uv run python scripts/fill_tables.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import config  # noqa: E402
import table1  # noqa: E402
from relay import report, results  # noqa: E402

HEADING = "## Appendix: results tables (computed from results.csv)"


def tables():
    run = sorted(config.PROBE_DIR.glob("run_*"))[-1]
    records, summary = table1.load_run(run)
    t1 = table1.build_table1(records, summary, table1.real_429s())
    table1.label_source(t1, summary, run.name)
    rows = results.read()
    parts = [("Table 1: Limits found in the real service", table1.render_markdown(t1)),
             ("Table 2a: Latency", report.table_2a(rows)),
             ("Table 2b: Outcomes", report.table_2b(rows)),
             ("Table 3: Retrieval settings", report.table_3(rows))]
    body = "\n\n".join(f"### {title}\n\n{text}" for title, text in parts)
    return (f"{HEADING}\n\nGenerated by `uv run python scripts/fill_tables.py` from "
            f"data/results.csv ({len(rows)} rows) and {run.name}. Do not edit by hand.\n\n"
            f"{body}\n")


def main():
    path = ROOT / "docs" / "WRITEUP.md"
    text = path.read_text()
    if HEADING not in text:
        raise SystemExit(f"{path} has no '{HEADING}' heading")
    path.write_text(text[:text.index(HEADING)] + tables())
    print(f"Tables written into {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
